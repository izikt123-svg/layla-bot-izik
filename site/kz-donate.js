/* ============================================================
   KZ DONATE — multi-rail donation modal
   Rails: Stripe Checkout (USD/EUR/ILS), Bit (phone QR), Paybox link,
   PayPal.me, Nedarim Plus, bank transfer. Receipts generated by
   the chosen rail (Stripe issues automatic receipts).

   Configure once on the page:
     window.KZ_DONATE_CFG = {
       paypalMe:     'YourPayPalUsername',
       bitPhone:     '050-0000000',
       payboxLink:   'https://payboxapp.page.link/...',
       nedarimPlus:  'https://www.matara.pro/nedarimplus/online?mosad=...',
       bankAccount:  { bank:'בנק לאומי', branch:'XXX', account:'XXXXXX', name:'שמך' },
       stripeEnabled: true,
       presetIls: [18, 36, 72, 180, 360, 720]
     };

   Open the modal anywhere via:
     <button onclick="KZ_DONATE.open()">תרומה</button>
   or click any element with class="js-kz-donate".
   ============================================================ */
(function(){
  'use strict';

  const DEFAULT = {
    paypalMe: '',
    bitPhone: '',
    payboxLink: '',
    nedarimPlus: '',
    bankAccount: null,
    stripeEnabled: false,
    presetIls: [18, 36, 72, 180, 360, 720],
    title: 'תרומה למרכז התפילה',
    subtitle: 'כל תרומה מאפשרת לעוד לב להתפלל. תודה רבה ❤️'
  };
  const cfg = () => Object.assign({}, DEFAULT, window.KZ_DONATE_CFG || {});

  function buildModal(){
    if (document.querySelector('.kz-donate-modal')) return;
    const c = cfg();
    const m = document.createElement('div');
    m.className = 'kz-donate-modal';
    m.setAttribute('role', 'dialog');
    m.setAttribute('aria-modal', 'true');
    m.setAttribute('aria-labelledby', 'kzDonateTitle');
    m.innerHTML = `
      <div class="kz-donate-back" data-close></div>
      <div class="kz-donate-card">
        <button class="kz-donate-x" aria-label="סגור" data-close>×</button>
        <div class="kz-donate-head">
          <div class="kz-donate-emoji">🕯</div>
          <h3 id="kzDonateTitle">${escapeHtml(c.title)}</h3>
          <p>${escapeHtml(c.subtitle)}</p>
        </div>
        <div class="kz-donate-amounts">
          ${c.presetIls.map((v,i) => `<button class="kz-amt ${i === 2 ? 'is-selected' : ''}" data-amt="${v}">₪${v}</button>`).join('')}
          <input class="kz-amt-custom" type="number" min="5" placeholder="סכום אחר ₪"/>
        </div>
        <div class="kz-donate-rails"></div>
        <div class="kz-donate-foot">
          <small>תרומות מטופלות ע"י השירות שתבחר. השירות הוא שמנפיק קבלה.</small>
        </div>
      </div>`;
    document.body.appendChild(m);
    const railsWrap = m.querySelector('.kz-donate-rails');
    railsWrap.append(...buildRails(m, c));

    // selected amount logic
    const amts = m.querySelectorAll('.kz-amt');
    amts.forEach(b => b.addEventListener('click', () => {
      amts.forEach(x => x.classList.remove('is-selected'));
      b.classList.add('is-selected');
      m.querySelector('.kz-amt-custom').value = '';
    }));

    m.addEventListener('click', (e) => {
      if (e.target.closest('[data-close]')) close();
    });
  }

  function selectedAmount(modal){
    const custom = parseInt(modal.querySelector('.kz-amt-custom').value, 10);
    if (custom && custom > 0) return custom;
    const sel = modal.querySelector('.kz-amt.is-selected');
    return parseInt(sel?.dataset.amt || '72', 10);
  }

  function buildRails(modal, c){
    const out = [];

    // Stripe
    if (c.stripeEnabled){
      const btn = railBtn('💳', 'Stripe — כרטיס אשראי בעולם', 'מנפיק קבלה אוטומטית · USD/EUR/ILS', 'kz-rail-stripe');
      btn.addEventListener('click', async () => {
        const amount = selectedAmount(modal);
        try {
          const r = await fetch('/api/donate-stripe', {
            method: 'POST', headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ amount, currency: 'ils' })
          });
          if (!r.ok) throw new Error('stripe');
          const { url } = await r.json();
          if (url) location.href = url;
        } catch { alert('Stripe לא פעיל כרגע — נסה שיטה אחרת'); }
      });
      out.push(btn);
    }
    // Bit
    if (c.bitPhone){
      const btn = railBtn('📱', 'Bit', `העברה ישירה למספר ${escapeHtml(c.bitPhone)}`, 'kz-rail-bit');
      btn.addEventListener('click', () => {
        const amount = selectedAmount(modal);
        showBitDetails(modal, c.bitPhone, amount);
      });
      out.push(btn);
    }
    // Paybox
    if (c.payboxLink){
      const btn = railLink('💼', 'Paybox', 'תשלום מאובטח · אפליקציית פייבוקס', 'kz-rail-paybox', c.payboxLink);
      out.push(btn);
    }
    // Nedarim Plus
    if (c.nedarimPlus){
      const btn = railLink('🕎', 'נדרים פלוס', 'תשלום עם קבלת מס (46א)', 'kz-rail-nedarim', c.nedarimPlus);
      out.push(btn);
    }
    // PayPal
    if (c.paypalMe){
      const btn = railBtn('🌐', 'PayPal', 'מתאים לתורמים מחו"ל', 'kz-rail-paypal');
      btn.addEventListener('click', () => {
        const amount = selectedAmount(modal);
        const url = `https://paypal.me/${encodeURIComponent(c.paypalMe)}/${amount}`;
        window.open(url, '_blank', 'noopener');
      });
      out.push(btn);
    }
    // Bank transfer
    if (c.bankAccount){
      const btn = railBtn('🏦', 'העברה בנקאית', `${c.bankAccount.bank} · סניף ${c.bankAccount.branch} · חשבון ${c.bankAccount.account}`, 'kz-rail-bank');
      btn.addEventListener('click', () => showBankDetails(modal, c.bankAccount));
      out.push(btn);
    }

    if (!out.length){
      const empty = document.createElement('div');
      empty.className = 'kz-donate-empty';
      empty.textContent = 'הגדר אמצעי תשלום ב-window.KZ_DONATE_CFG';
      out.push(empty);
    }
    return out;
  }

  function railBtn(icn, title, sub, cls){
    const b = document.createElement('button');
    b.className = `kz-rail ${cls}`;
    b.type = 'button';
    b.innerHTML = `<span class="kz-rail-icn">${icn}</span>
      <span class="kz-rail-text"><b>${escapeHtml(title)}</b><small>${escapeHtml(sub)}</small></span>
      <span class="kz-rail-arrow">←</span>`;
    return b;
  }
  function railLink(icn, title, sub, cls, href){
    const a = document.createElement('a');
    a.className = `kz-rail ${cls}`;
    a.href = href; a.target = '_blank'; a.rel = 'noopener';
    a.innerHTML = `<span class="kz-rail-icn">${icn}</span>
      <span class="kz-rail-text"><b>${escapeHtml(title)}</b><small>${escapeHtml(sub)}</small></span>
      <span class="kz-rail-arrow">↗</span>`;
    return a;
  }

  function showBitDetails(modal, phone, amount){
    const overlay = document.createElement('div');
    overlay.className = 'kz-donate-step';
    overlay.innerHTML = `
      <button class="kz-donate-back-btn" data-back>← חזור</button>
      <div class="kz-bit-info">
        <h4>תרומה דרך Bit</h4>
        <p>שלחו <b>₪${amount}</b> למספר:</p>
        <div class="kz-bit-phone">${escapeHtml(phone)}</div>
        <button class="kz-bit-copy">העתק מספר</button>
        <p class="kz-bit-note">פתחו את אפליקציית Bit · "שלח כסף" · הדביקו את המספר.</p>
      </div>`;
    modal.querySelector('.kz-donate-card').appendChild(overlay);
    overlay.querySelector('.kz-bit-copy').addEventListener('click', async () => {
      try { await navigator.clipboard.writeText(phone); overlay.querySelector('.kz-bit-copy').textContent = '✓ הועתק'; } catch {}
    });
    overlay.querySelector('[data-back]').addEventListener('click', () => overlay.remove());
  }

  function showBankDetails(modal, b){
    const overlay = document.createElement('div');
    overlay.className = 'kz-donate-step';
    overlay.innerHTML = `
      <button class="kz-donate-back-btn" data-back>← חזור</button>
      <div class="kz-bank-info">
        <h4>העברה בנקאית</h4>
        <ul>
          <li>בנק: <b>${escapeHtml(b.bank)}</b></li>
          <li>סניף: <b>${escapeHtml(b.branch)}</b></li>
          <li>חשבון: <b>${escapeHtml(b.account)}</b></li>
          <li>על שם: <b>${escapeHtml(b.name)}</b></li>
        </ul>
        <p class="kz-bit-note">לקבלת קבלה — שלחו אישור העברה ל-tzedaka@my-hom.net</p>
      </div>`;
    modal.querySelector('.kz-donate-card').appendChild(overlay);
    overlay.querySelector('[data-back]').addEventListener('click', () => overlay.remove());
  }

  function open(){ buildModal(); requestAnimationFrame(() => document.querySelector('.kz-donate-modal').classList.add('is-open')); }
  function close(){
    const m = document.querySelector('.kz-donate-modal');
    if (!m) return;
    m.classList.remove('is-open');
    setTimeout(() => m.remove(), 300);
  }

  function escapeHtml(s){
    return String(s ?? '').replace(/[&<>"']/g, m => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[m]));
  }

  // Auto-wire any element with class js-kz-donate
  document.addEventListener('click', (e) => {
    if (e.target.closest('.js-kz-donate')){ e.preventDefault(); open(); }
  });

  window.KZ_DONATE = { open, close };
})();
